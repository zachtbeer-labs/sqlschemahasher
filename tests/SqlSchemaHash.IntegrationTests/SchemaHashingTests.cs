    [TestMethod]
    public async Task AutoGeneratedIndexNames_WithoutNormalization_ProduceDifferentHashes()
    {
        // Arrange - Two databases with inline PKs that get auto-generated index names
        var db1Name = await CreateTestDatabaseAsync("AutoIdx_Norm1");
        var db2Name = await CreateTestDatabaseAsync("AutoIdx_Norm2");

        // Inline PRIMARY KEY causes SQL Server to generate PK index names with random hex suffixes
        await ExecuteSqlAsync(db1Name, @"
            CREATE TABLE Products (
                ProductId INT IDENTITY(1,1) PRIMARY KEY,
                Name NVARCHAR(100) NOT NULL
            )");
        await ExecuteSqlAsync(db2Name, @"
            CREATE TABLE Products (
                ProductId INT IDENTITY(1,1) PRIMARY KEY,
                Name NVARCHAR(100) NOT NULL
            )");

        // Act
        var defaultOptions = new SchemaHashOptions { Modules = ModuleNormalization.IgnoreBodyText };
        var normalizedOptions = new SchemaHashOptions { Indexes = IndexNormalization.NormalizeAutoGeneratedNames, Constraints = ConstraintNormalization.NormalizeAutoGeneratedNames, Modules = ModuleNormalization.IgnoreBodyText };

        var defaultHash1 = await ExtractAndHashAsync(db1Name, defaultOptions);
        var defaultHash2 = await ExtractAndHashAsync(db2Name, defaultOptions);

        var normalizedHash1 = await ExtractAndHashAsync(db1Name, normalizedOptions);
        var normalizedHash2 = await ExtractAndHashAsync(db2Name, normalizedOptions);

        // Assert - auto-generated PK names differ across databases, so hashes differ without normalization
        defaultHash1.ShouldNotBe(defaultHash2, "Auto-generated PK index names should cause different hashes without normalization");
        // With normalization, the GUID suffixes are stripped and hashes should match
        normalizedHash1.ShouldBe(normalizedHash2, "With normalization enabled, auto-generated PK index names should be ignored");
    }

