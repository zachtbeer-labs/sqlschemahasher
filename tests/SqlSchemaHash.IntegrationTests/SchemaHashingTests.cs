    [TestMethod]
    public async Task HashWithNormalization_IgnoresAutoGeneratedIndexNames()
    {
        // Arrange - Create two databases where indexes have different auto-generated suffixes
        var db1Name = await CreateTestDatabaseAsync("HashTest_IndexNorm1");
        var db2Name = await CreateTestDatabaseAsync("HashTest_IndexNorm2");

        await CreateSchemaWithNamedIndex(db1Name, "IX_Employees_Name_ABC12345DEF67890");
        await CreateSchemaWithNamedIndex(db2Name, "IX_Employees_Name_123456789ABCDEF0");

        // Act - With normalization enabled
        var normalizedOptions = new SchemaHashOptions { Indexes = IndexNormalization.NormalizeAutoGeneratedNames, Constraints = ConstraintNormalization.NormalizeAutoGeneratedNames };
        var exactOptions = new SchemaHashOptions();

        var normalizedHash1 = await ExtractAndHashAsync(db1Name, normalizedOptions);
        var normalizedHash2 = await ExtractAndHashAsync(db2Name, normalizedOptions);

        var exactHash1 = await ExtractAndHashAsync(db1Name, exactOptions);
        var exactHash2 = await ExtractAndHashAsync(db2Name, exactOptions);

        // Assert
        normalizedHash1.ShouldBe(normalizedHash2, "Normalized hashes should match when only index name suffixes differ");
        exactHash1.ShouldNotBe(exactHash2, "Exact hashes should differ when index names are different");
    }

