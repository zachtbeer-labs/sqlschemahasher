    public async Task SchemaFilter_IncludesOnlyMatchingSchema()
    {
        // Arrange
        var dbName = await CreateTestDatabaseAsync("Filter_Schema");

        await ExecuteSqlAsync(dbName, "CREATE SCHEMA sales");
        await ExecuteSqlAsync(dbName, "CREATE TABLE dbo.DboTable (Id INT PRIMARY KEY)");
        await ExecuteSqlAsync(dbName, "CREATE TABLE sales.SalesTable (Id INT PRIMARY KEY)");
        await ExecuteSqlAsync(dbName, @"CREATE PROCEDURE dbo.DboProc AS BEGIN SELECT 1 END");
        await ExecuteSqlAsync(dbName, @"CREATE PROCEDURE sales.SalesProc AS BEGIN SELECT 1 END");

        // Act
        var salesOptions = new SchemaHashOptions { SchemaFilter = "sales" };
        var filteredSchema = await ExtractSchemaAsync(dbName, salesOptions);
        var filteredHash = await ExtractAndHashAsync(dbName, salesOptions);
        var unfilteredHash = await ExtractAndHashAsync(dbName);

        // Assert - only sales objects
        filteredSchema.Tables.ShouldAllBe(t => t.SchemaName == "sales", "Should only contain sales tables");
        filteredSchema.Tables.Count.ShouldBe(1);
        filteredSchema.StoredProcedures.ShouldAllBe(p => p.SchemaName == "sales", "Should only contain sales procs");
        filteredSchema.StoredProcedures.Count.ShouldBe(1);

        // Filtered hash should differ from unfiltered
        filteredHash.ShouldNotBe(unfilteredHash, "Filtered hash should differ from unfiltered");
    }

